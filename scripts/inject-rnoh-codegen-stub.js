#!/usr/bin/env node
/**
 * Write the one generated TypeScript file the adapted ble-plx har imports.
 *
 * `@react-native-oh-tpl/react-native-ble-plx`'s `BlePlxModule.ts` contains
 *
 *     import { TM } from '@rnoh/react-native-openharmony/generated/ts'
 *     export class BlePlxModule ... implements TM.BlePlx.Spec, BlePlxInterface
 *
 * In a stock RNOH project the `@rnoh/hvigor-plugin` codegen writes
 * `generated/ts` into the ohpm-installed RNOH har. This app deliberately has
 * no hvigor plugin, no codegen and no autolinking (it registers every package
 * by hand — see docs/harmony-setup.md), so that file does not exist and the
 * ArkTS compile stops with
 *
 *     ERROR: 10505001 Cannot find module
 *     '@rnoh/react-native-openharmony/generated/ts'
 *
 * The import is used only in an `implements` clause. `BlePlxModule` also
 * implements its own `BlePlxInterface`, which declares every method, so
 * writing an empty `TM.BlePlx.Spec` keeps the module fully type-checked while
 * letting the har compile. This is a build product, not source: the file is
 * written into `harmony/oh_modules`, which is gitignored, and `ohpm install`
 * recreates the directory on every clean build.
 *
 * Usage (after `ohpm install --all`, before `hvigorw assembleHap`):
 *
 *     node scripts/inject-rnoh-codegen-stub.js
 */
const fs = require('fs');
const path = require('path');

const HARMONY = path.join(__dirname, '..', 'harmony');
const OHPM = path.join(HARMONY, 'oh_modules', '.ohpm');
const RNOH_PREFIX = '@rnoh+react-native-openharmony@';

const STUB = `/**
 * Generated by scripts/inject-rnoh-codegen-stub.js — do not edit by hand.
 *
 * This app has no RNOH codegen, so the type namespace that the adapted
 * react-native-ble-plx har imports for \`TM.BlePlx.Spec\` is provided here.
 * The module's own \`BlePlxInterface\` declares its methods, so an empty Spec
 * does not weaken the type check of the module.
 */
export namespace TM {
  export namespace BlePlx {
    export interface Spec {}
  }
}
`;

function main() {
  if (!fs.existsSync(OHPM)) {
    console.error(
      `ohpm install has not run yet: ${path.relative(
        process.cwd(),
        OHPM,
      )} is missing`,
    );
    return 1;
  }

  const packages = fs
    .readdirSync(OHPM)
    .filter(name => name.startsWith(RNOH_PREFIX));
  if (packages.length === 0) {
    console.error(
      `no ${RNOH_PREFIX}<version> package under ${path.relative(
        process.cwd(),
        OHPM,
      )}; run \`ohpm install --all\` in harmony/ first`,
    );
    return 1;
  }

  for (const name of packages) {
    const packageDir = path.join(
      OHPM,
      name,
      'oh_modules',
      '@rnoh',
      'react-native-openharmony',
    );
    if (!fs.existsSync(packageDir)) {
      continue;
    }
    const generatedDir = path.join(packageDir, 'generated');
    const target = path.join(generatedDir, 'ts.ts');
    if (fs.existsSync(target)) {
      console.log(`kept existing ${path.relative(process.cwd(), target)}`);
      continue;
    }
    fs.mkdirSync(generatedDir, {recursive: true});
    fs.writeFileSync(target, STUB);
    console.log(`wrote ${path.relative(process.cwd(), target)}`);
  }

  return 0;
}

process.exitCode = main();
